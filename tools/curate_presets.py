"""Curate the browser by normalized spectrum and envelope; keep legacy IDs intact."""
from pathlib import Path
import json,re,sys
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
ENG=['PIANO','KEYS','PAD','GLASS','BASS','DRUMKIT','WORLD','KALIMBA','WINDS','SYNTH','PLUCK','LEAD']
cache=ROOT/'build/test/curation-features.npz'
if not cache.exists() or '--refresh' in sys.argv:
 from dup_check import features,load
 sound_root=ROOT/'build/test/palette-final'
 if '--sounds' in sys.argv:sound_root=Path(sys.argv[sys.argv.index('--sounds')+1])
 files=sorted(sound_root.glob('*/*.wav'))
 if not files:raise SystemExit('Render factory WAVs first, then use --sounds OUTDIR --refresh')
 values=[features(load(str(p))) for p in files]
 cache.parent.mkdir(parents=True,exist_ok=True)
 np.savez(cache,paths=[str(p) for p in files],spec=[v[0] for v in values],env=[v[1] for v in values])
data=np.load(cache)
source=(ROOT/'tapes/overworld/tape_dsp.c').read_text(encoding='utf8')
latest=set();recent=set()
for name,target in [('palette-presets.json',latest),('underground-presets.json',recent)]:
 for r in json.loads((ROOT/'out'/name).read_text()):target.add((r['engine'],r['bank'],r['slot']))
pinned={(e,b,0) for e in range(12) for b in range(4)}
a=source.index('static const uint8_t KEYS_SET');b=source.index('};',a)
for e,p in re.findall(r'\{(\d+),\s*(\d+)\}',source[a:b]):pinned.add((int(e),0,int(p)))
items=[]
for i,path in enumerate(data['paths']):
 p=Path(str(path));m=re.match(r'b(\d)_(\d+)_(.*)\.wav',p.name)
 e=ENG.index(p.parent.name);key=(e,int(m[1]),int(m[2])-1)
 items.append(dict(key=key,engine=e,bank=key[1],slot=key[2],name=m[3].replace('_',' '),path=str(p),index=i))
priority=lambda r:(r['key'] not in pinned,r['key'] not in latest,r['key'] not in recent,r['bank'],r['slot'])
kept=[];removed=[]
for r in sorted(items,key=priority):
 nearest=None
 for q in kept:
  if q['engine']!=r['engine']:continue
  ds=float(np.abs(data['spec'][r['index']]-data['spec'][q['index']]).mean())
  de=float(np.abs(data['env'][r['index']]-data['env'][q['index']]).mean())
  if ds<1.25 and de<2.2 and (nearest is None or ds+de*0.3<nearest[0]):nearest=(ds+de*0.3,q,ds,de)
 if nearest and r['key'] not in pinned:
  removed.append(dict(**r,replacement={k:nearest[1][k] for k in ('engine','bank','slot','name')},spectrum_db=nearest[2],envelope_db=nearest[3]))
 else:kept.append(r)
masks=[0]*48
for r in kept:masks[r['engine']*4+r['bank']]|=1<<r['slot']
header='/* Generated by tools/curate_presets.py. Raw preset IDs remain loadable. */\nstatic const uint16_t BROWSE_MASK[48] = {\n'
for e in range(12):header+='    '+', '.join(f'0x{m:03x}' for m in masks[e*4:e*4+4])+',\n'
(ROOT/'tapes/overworld/browse_mask.h').write_text(header+'};\n')
result=dict(total=len(items),visible=len(kept),hidden=len(removed),hidden_previous=sum(r['key'] not in latest for r in removed),masks=masks,kept=kept,removed=removed)
(ROOT/'out/preset-curation.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf8')
print('Total / kept / hidden / previous:',len(items),len(kept),len(removed),result['hidden_previous'])
for r in removed[:15]:print(ENG[r['engine']],r['name'],'->',r['replacement']['name'])
